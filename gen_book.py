import random

SEED = 1

random.seed(SEED)

NULL = 0xFFF
SLOTS = NULL

# symbol/Buy or Sell: (Mean Price, StD Price, Mean Qty, StD Qty, Mean Orders, StD Orders)
# Each pair (0 and 1) or (2 and 3) Represent first the sell and then the buy
