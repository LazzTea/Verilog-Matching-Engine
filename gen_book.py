def entry(nxt, qty, price):
  return (nxt << 20) | (qty << 11) | (price << 1) | 1

book = [0] * SLOTS
heads = [NULL] * 32
slot = 0

table = {k: [] for k in range(32)}

# Main Code

# First Generate the Table

# random.normalvariate()

for symbol, (mp, sp, mq, sq, mo, so) in SYMBOLS.items():
  for i in range(round(random.normalvariate(mo, so))):
    price = round(random.normalvariate(mp, sp))
    qty = round(random.normalvariate(mq, sq))

    if (price <= 0 or qty <= 0):
      continue

    if (symbol % 2 == 0 and price <= mp):
      table[symbol].append((price, qty))
    elif (symbol % 2 == 1 and price > mp):
      table[symbol].append((price, qty))

  table[symbol].sort(key=lambda t: t[0])

# Populate the Book with the table

while table:
  # Get Random Symbol from Table
  sym = random.choice(list(table))

  # Get Random Order from Symbol List
  if table[sym]:
    order = random.choice(table[sym])
    table[sym].remove(order)
  else:
    table.pop(sym)

  # Place Into Order Book
  if (slot >= SLOTS):
    break
  
  book[slot] = (order[0], order[1], NULL)
  
  if (heads[sym] == NULL):
    heads[sym] = slot
  else:
    next = heads[sym]
    while (book[next][2] != NULL):
      next = book[next][2]
    
    book[next] = (book[next][0], book[next][1], slot)
  
  slot = slot + 1

# For Testing
print('Order Book by Slot')
for b in book:
  print(f'Price, Quantity, Next : {b}')

print("-----------------------------------------------\n")
print ("Order Book by Symbol")

indx = 0
for head in heads:
  print(f'Symbol {indx}')

  if (head != NULL):
    next = head
    while (next != NULL):
      if (book[next] != 0):
        print(f'Price {book[next][0]}, Quantity {book[next][1]}, Next {book[next][2]}')
        next = book[next][2]
      else:
        print(0)
  else:
    print(f'No Orders for {indx}')
  indx = indx + 1


with open("tables/order_book.mem", "w") as f:
  f.write("// generated by gen_book.py\n")
  for e in book:
    if (isinstance(e, tuple)):
      e = entry(e[2], e[1], e[0])
    f.write(f"{e:08X}\n")

with open("tables/head_table.mem", "w") as f:
  f.write("// generated by gen_book.py\n")
  for h in heads:
    f.write(f"{h:03X}\n")

print(f"Wrote {slot} orders.")
print(f"Set PRELOAD_COUNT = {slot}")

